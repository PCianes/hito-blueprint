#!/bin/sh
# Builds AGENTS.md from blueprint/rules and custom/rules.
#   rules.sh          write AGENTS.md
#   rules.sh --check  fail if AGENTS.md differs from what would be written
set -eu
export LC_ALL=C  # the same order of my-*.md rules on every machine

root=${HITO_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}
base="$root/blueprint/rules"
custom="$root/custom/rules"
disable="$root/custom/disable"
out="$root/AGENTS.md"

fail() { echo "rules: $*" >&2; exit 1; }
listed() { printf '%s\n' "$names" | grep -qxF "$1"; }

[ -f "$base/ORDER" ] || fail "blueprint/rules/ORDER is missing"
names=$(tr -d '\r' < "$base/ORDER" | grep -v '^[[:space:]]*$' || true)
dups=$(printf '%s\n' "$names" | sort | uniq -d)
[ -z "$dups" ] || fail "ORDER lists a rule more than once: $dups"

# Nothing in blueprint/rules or custom/ may be silently ignored: anything the base does not
# read is a mistake (a misspelled name, a wrong extension, a folder) and fails here.
unknown() { fail "$1 is not something the base reads; see blueprint/README.md"; }
for f in "$base"/* "$base"/.[!.]* "$base"/..?*; do
  [ -e "$f" ] || continue
  case ${f##*/} in
    (ORDER | .markdownlint-cli2.yaml | .DS_Store) ;;
    (.*) unknown "blueprint/rules/${f##*/}" ;;
    (*.md) [ -f "$f" ] || unknown "blueprint/rules/${f##*/}" ;;
    (*) unknown "blueprint/rules/${f##*/}" ;;
  esac
done
if [ -d "$root/custom" ]; then
  for f in "$root"/custom/* "$root"/custom/.[!.]* "$root"/custom/..?*; do
    [ -e "$f" ] || continue
    case ${f##*/} in
      (README.md | rules | skills | git-hooks | disable | .DS_Store) ;;
      (*) unknown "custom/${f##*/}" ;;
    esac
  done
fi
for f in "$custom"/* "$custom"/.[!.]* "$custom"/..?*; do
  [ -e "$f" ] || continue
  case ${f##*/} in
    (.markdownlint-cli2.yaml | .DS_Store) ;;
    (.*) unknown "custom/rules/${f##*/}" ;;
    (*.md) [ -f "$f" ] || unknown "custom/rules/${f##*/}" ;;
    (*) unknown "custom/rules/${f##*/}" ;;
  esac
done
for f in "$root"/custom/git-hooks/* "$root"/custom/git-hooks/.[!.]* "$root"/custom/git-hooks/..?*; do
  [ -e "$f" ] || continue
  case ${f##*/} in
    (commit-msg | .DS_Store) ;;
    (test-*.sh) [ -f "$f" ] || unknown "custom/git-hooks/${f##*/}" ;;
    (*) unknown "custom/git-hooks/${f##*/}" ;;
  esac
done

# ORDER and the base files must match one to one.
for n in $names; do
  [ -f "$base/$n.md" ] || fail "ORDER lists '$n' but blueprint/rules/$n.md does not exist"
done
for f in "$base"/*.md; do
  [ -e "$f" ] || continue
  n=$(basename "$f" .md)
  listed "$n" || fail "blueprint/rules/$n.md is not listed in ORDER"
done

# A custom rule either replaces a base rule or is an own rule named my-*.
for f in "$custom"/*.md; do
  [ -e "$f" ] || continue
  n=$(basename "$f" .md)
  case $n in my-*) continue ;; esac
  listed "$n" || fail "custom/rules/$n.md replaces no base rule (own rules are named my-*.md)"
done

# Disabled rules must exist and must not also be replaced.
disabled=" "
if [ -f "$disable" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    line=$(printf '%s' "$line" | tr -d '\r')
    case $line in '' | '#'*) continue ;; (skills/*) continue ;; esac  # skills.sh checks those
    n=${line#rules/}
    [ "$n" != "$line" ] || fail "custom/disable: '$line' must look like rules/<name> or skills/<name>"
    listed "$n" || fail "custom/disable: there is no base rule named '$n'"
    [ ! -f "$custom/$n.md" ] || fail "rule '$n' is both replaced and disabled"
    disabled="$disabled$n "
  done < "$disable"
fi

render() {
  echo "# Rules"
  echo
  echo "> Generated by \`blueprint/scripts/rules.sh\` from \`blueprint/rules/\` and \`custom/\`. Do not edit by hand."
  for n in $names; do
    case $disabled in *" $n "*) continue ;; esac
    echo
    if [ -f "$custom/$n.md" ]; then tr -d '\r' < "$custom/$n.md"; else tr -d '\r' < "$base/$n.md"; fi
  done
  for f in "$custom"/my-*.md; do
    [ -e "$f" ] || continue
    echo
    tr -d '\r' < "$f"
  done
}

if [ "${1:-}" = "--check" ]; then
  [ -f "$out" ] || fail "AGENTS.md is missing; run blueprint/scripts/rules.sh"
  tmpout=$(mktemp)
  trap 'rm -f "$tmpout"' EXIT
  tr -d '\r' < "$out" > "$tmpout"  # line endings are not content
  render | cmp -s - "$tmpout" || fail "AGENTS.md is out of date or was edited by hand; run blueprint/scripts/rules.sh"
else
  render > "$out"
fi
